routes = []

def add_url(path: str, changefreq: str = "daily", priority: str = "0.9"):
    # 슬래시는 보존하면서 한글 및 특수문자 안전 인코딩
    encoded_path = quote(path, safe="/")
    routes.append({
        "loc": f"{BASE_URL}{encoded_path}",
        "changefreq": changefreq,
        "priority": priority
    })

